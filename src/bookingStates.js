function assertTransition(from, to) {
  const normFrom = normalizeState(from);
  const normTo = normalizeState(to);
  const allowed = TRANSITIONS[normFrom] || [];
  if (!allowed.includes(normTo)) {
    throw new HttpError(409, 'INVALID_STATE', `Invalid state transition from ${normFrom} to ${normTo}.`);
  }
}

