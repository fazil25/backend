function normalizeState(state) {
  if (!state) return BOOKING_STATES.PENDING;
  const upper = String(state).trim().toUpperCase();
  if (BOOKING_STATES[upper]) return BOOKING_STATES[upper];
  const lower = String(state).trim().toLowerCase();
  return LEGACY_STATE_MAP[lower] || upper;
}

