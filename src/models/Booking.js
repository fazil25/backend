const mongoose = require('mongoose');

const serviceAddressSchema = new mongoose.Schema(
  {
    formattedAddress: { type: String, required: true },
    houseNumber: { type: String, default: '' },
    street: { type: String, default: '' },
    area: { type: String, default: '' },
    locality: { type: String, default: '' },
    city: { type: String, default: '' },
    district: { type: String, default: '' },
    state: { type: String, default: '' },
    pincode: { type: String, default: '' },
    postalCode: { type: String, default: '' },
    country: { type: String, default: 'India' },
    landmark: { type: String, default: '' },
    mobileNumber: { type: String, default: '' },
    latitude: { type: Number, required: true },
    longitude: { type: Number, required: true },
    accuracy: { type: Number, default: null },
    addressId: { type: String, default: null },
    source: { type: String, enum: ['GPS', 'SEARCH', 'SAVED_ADDRESS', 'MAP_PIN', 'MANUAL'], default: 'GPS' },
    confirmedAt: { type: Date, default: Date.now },
  },
  { _id: false }
);

const bookingSchema = new mongoose.Schema(
  {
    customId: { type: String, unique: true, sparse: true, index: true },
    customer: { type: mongoose.Schema.Types.ObjectId, ref: 'User' },
    customerId: { type: String, index: true },
    customerName: { type: String, required: true },
    customerPhone: { type: String },
    worker: { type: mongoose.Schema.Types.ObjectId, ref: 'User' },
    providerId: { type: String, index: true, default: null },
    providerName: { type: String, default: null },
    providerPhone: { type: String, default: null },
    service: { type: String, required: true, index: true },
    category: { type: String, required: true, index: true },
    date: { type: String },
    time: { type: String },
    scheduledAt: { type: Date, default: Date.now, index: true },
    address: { type: String, required: true },
    area: { type: String, default: '' },
    city: { type: String, default: '' },
    state: { type: String, default: '' },
    pincode: { type: String, default: '' },
    // Permanent structured address snapshot
    serviceAddress: { type: serviceAddressSchema, default: null },
    location: {
      address: { type: String },
      area: { type: String },
      city: { type: String },
      state: { type: String },
      pincode: { type: String },
      latitude: { type: Number },
      longitude: { type: Number },
    },
    latitude: { type: Number, required: true },
    longitude: { type: Number, required: true },
    locationAccuracy: { type: Number, default: null },
    workerLatitude: { type: Number, default: null },
    workerLongitude: { type: Number, default: null },
    workerHeading: { type: Number, default: null },
    locationLastUpdatedAt: { type: Date, default: null },
    distanceKm: { type: Number, default: null },
    price: { type: String, required: true },
    priceNum: { type: Number, default: 499 },
    priceBreakdown: { type: mongoose.Schema.Types.Mixed },
    status: {
      type: String,
      enum: [
        'PENDING',
        'CONFIRMED',
        'WORKER_ASSIGNED',
        'WORKER_ACCEPTED',
        'TRAVELLING',
        'ARRIVED',
        'ENTERED_HOME',
        'WORK_STARTED',
        'WORK_FINISHED',
        'CUSTOMER_CONFIRMED',
        'PAYMENT_COMPLETED',
        'COMPLETED',
        'CANCELLED',
        'EXPIRED',
        'DECLINED',
        'TIME_CHANGE_REQUESTED',
        'TIME_CHANGE_ACCEPTED',
        'TIME_CHANGE_REJECTED',
      ],
      default: 'PENDING',
      index: true,
    },
    startOtp: {
      type: String,
      default: () => Math.floor(1000 + Math.random() * 9000).toString(),
    },
    etaMinutes: { type: Number, default: null },
    enteredHomeAt: { type: Date, default: null },
    workStartedAt: { type: Date, default: null },
    finishedAt: { type: Date, default: null },
    quote: { type: mongoose.Schema.Types.Mixed, default: null },
    paymentStatus: {
      type: String,
      enum: [
        'PENDING',
        'CREATED',
        'AUTHORIZED',
        'PAID',
        'CAPTURED',
        'SETTLED',
        'Settled',
        'PARTIALLY_REFUNDED',
        'REFUNDED',
        'FAILED',
        'CANCELLED',
        'Paid Online',
        'Cash on Delivery',
        'Cash on Service',
      ],
      default: 'PENDING',
    },
    paymentMethod: { type: String, default: 'Pay Online' },
    rating: { type: Number, default: null },
    review: { type: String, default: null },
    moderationStatus: { type: String, default: 'Approved' },
    photos: [String],
    beforePhotos: [String],
    afterPhotos: [String],
    diagnosis: { type: String, default: null },
    workPerformed: { type: String, default: null },
    partsUsed: [{ name: String, cost: Number }],
    isGuaranteeRevisit: { type: Boolean, default: false, index: true },
    originalBookingId: { type: String, default: null, index: true },
    guaranteeId: { type: String, default: null, index: true },
    revisitReason: { type: String, default: null },
    revisitOriginalIssue: { type: String, default: null },
    chatLocked: { type: Boolean, default: false },
    declinedByWorkers: [{ type: String }],
    cancellationReason: { type: String, default: null },
    refundAmount: { type: Number, default: 0 },
    refundStatus: {
      type: String,
      enum: ['NONE', 'NOT_APPLICABLE', 'INITIATED', 'PROCESSING', 'REFUNDED', 'FAILED'],
      default: 'NONE',
    },
    refundMethod: { type: String, default: null },
    providerIsVerified: { type: Boolean, default: false },
    invoiceNumber: { type: String, default: null },
    invoiceUrl: { type: String, default: null },
    timeChangeRequest: {
      requestedTime: String,
      reason: String,
      status: { type: String, default: 'Pending' },
      requestedBy: String,
      requestedAt: Date,
    },
    history: [
      {
        from: String,
        to: String,
        by: String,
        role: String,
        action: String,
        at: { type: Date, default: Date.now },
        note: String,
      },
    ],
  },
  { timestamps: true }
);

bookingSchema.index({ customerId: 1, createdAt: -1 });
bookingSchema.index({ providerId: 1, status: 1 });
bookingSchema.index({ providerId: 1, status: 1, service: 1, createdAt: -1 });
bookingSchema.index({ status: 1, service: 1 });
bookingSchema.index({ status: 1, createdAt: -1 });
bookingSchema.index({ scheduledAt: 1, status: 1 });
bookingSchema.index({ createdAt: -1 });

module.exports = mongoose.model('Booking', bookingSchema);
